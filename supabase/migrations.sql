-- ---------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;


-- ---------------------------------------------------------------------
-- Single-row tables (always id = 1)
-- ---------------------------------------------------------------------

create table if not exists public.profile (
  id               smallint primary key default 1 check (id = 1),
  full_name        text not null default '',
  title            text,
  short_intro      text,
  bio              text,
  location         text,
  email            text,
  phone            text,
  birthday         date,
  photo_url        text,
  photo_path       text,
  about_photo_url  text,
  about_photo_path text,
  cv_url           text,
  cv_path          text,
  updated_at       timestamptz not null default now()
);

create table if not exists public.settings (
  id               smallint primary key default 1 check (id = 1),
  site_title       text not null default '',
  meta_description text,
  accent_color     text not null default '#b3441e' check (accent_color ~* '^#[0-9a-f]{6}$'),
  copyright_text   text,
  favicon_url      text,
  favicon_path     text,
  updated_at       timestamptz not null default now()
);

-- Interface text (button and form labels, …) as { key: text }. Missing
-- keys fall back to the defaults in client/src/lib/uiText.js.
create table if not exists public.ui_text (
  id         smallint primary key default 1 check (id = 1),
  texts      jsonb not null default '{}'::jsonb check (jsonb_typeof(texts) = 'object'),
  updated_at timestamptz not null default now()
);

drop trigger if exists profile_set_updated_at on public.profile;
create trigger profile_set_updated_at
  before update on public.profile
  for each row execute function public.set_updated_at();

drop trigger if exists settings_set_updated_at on public.settings;
create trigger settings_set_updated_at
  before update on public.settings
  for each row execute function public.set_updated_at();

drop trigger if exists ui_text_set_updated_at on public.ui_text;
create trigger ui_text_set_updated_at
  before update on public.ui_text
  for each row execute function public.set_updated_at();


-- ---------------------------------------------------------------------
-- Section visibility (one row per public section)
-- ---------------------------------------------------------------------

create table if not exists public.section_visibility (
  key        text primary key check (key in (
               'hero', 'about', 'skills', 'experience', 'education',
               'projects', 'certificates', 'testimonials', 'contact')),
  title      text not null default '',
  intro      text,
  sort_order integer not null default 0,
  is_visible boolean not null default true
);


-- ---------------------------------------------------------------------
-- List tables (all have sort_order and is_visible)
-- ---------------------------------------------------------------------

create table if not exists public.social_links (
  id         bigint generated by default as identity primary key,
  platform   text not null,
  url        text not null,
  sort_order integer not null default 0,
  is_visible boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.skill_categories (
  id         bigint generated by default as identity primary key,
  name       text not null,
  sort_order integer not null default 0,
  is_visible boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.skills (
  id          bigint generated by default as identity primary key,
  category_id bigint not null references public.skill_categories (id) on delete cascade,
  name        text not null,
  level       smallint check (level between 0 and 100),
  sort_order  integer not null default 0,
  is_visible  boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists public.experience (
  id          bigint generated by default as identity primary key,
  company     text not null,
  role        text not null,
  location    text,
  start_date  date not null,
  end_date    date,
  is_current  boolean not null default false,
  description text,
  sort_order  integer not null default 0,
  is_visible  boolean not null default true,
  created_at  timestamptz not null default now(),
  check (end_date is null or end_date >= start_date)
);

create table if not exists public.education (
  id          bigint generated by default as identity primary key,
  school      text not null,
  degree      text,
  start_year  integer check (start_year between 1900 and 2100),
  end_year    integer check (end_year between 1900 and 2100),
  description text,
  sort_order  integer not null default 0,
  is_visible  boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists public.projects (
  id             bigint generated by default as identity primary key,
  slug           text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  title          text not null,
  summary        text,
  description    text,
  tech_tags      text[] not null default '{}',
  live_url       text,
  repo_url       text,
  thumbnail_url  text,
  thumbnail_path text,
  sort_order     integer not null default 0,
  is_visible     boolean not null default true,
  created_at     timestamptz not null default now()
);

create table if not exists public.project_images (
  id         bigint generated by default as identity primary key,
  project_id bigint not null references public.projects (id) on delete cascade,
  image_url  text not null,
  image_path text,
  caption    text,
  sort_order integer not null default 0,
  is_visible boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.certificates (
  id             bigint generated by default as identity primary key,
  title          text not null,
  issuer         text,
  issued_on      date,
  credential_url text,
  image_url      text,
  image_path     text,
  sort_order     integer not null default 0,
  is_visible     boolean not null default true,
  created_at     timestamptz not null default now()
);

create table if not exists public.testimonials (
  id         bigint generated by default as identity primary key,
  name       text not null,
  role       text,
  quote      text not null,
  photo_url  text,
  photo_path text,
  sort_order integer not null default 0,
  is_visible boolean not null default true,
  created_at timestamptz not null default now()
);

-- Contact form inbox. Not a public content list, so it has no
-- sort_order / is_visible: messages are ordered by created_at.
create table if not exists public.messages (
  id         bigint generated by default as identity primary key,
  name       text not null check (char_length(name) between 1 and 100),
  email      text not null check (char_length(email) between 3 and 200),
  subject    text check (char_length(subject) <= 200),
  body       text not null check (char_length(body) between 1 and 5000),
  is_read    boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists skills_category_sort_idx on public.skills (category_id, sort_order);
create index if not exists project_images_project_sort_idx on public.project_images (project_id, sort_order);
create index if not exists messages_created_at_idx on public.messages (created_at desc);
create index if not exists messages_unread_idx on public.messages (is_read) where not is_read;


