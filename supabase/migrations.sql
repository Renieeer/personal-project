-- ---------------------------------------------------------------------
-- Row Level Security
--   anon / authenticated: SELECT visible rows only
--   anon / authenticated: INSERT into messages only
--   Every other write goes through the Express API (service role,
--   which bypasses RLS). No other policies exist, so all other
--   writes from the browser are denied.
-- ---------------------------------------------------------------------

alter table public.profile            enable row level security;
alter table public.settings           enable row level security;
alter table public.ui_text            enable row level security;
alter table public.section_visibility enable row level security;
alter table public.social_links       enable row level security;
alter table public.skill_categories   enable row level security;
alter table public.skills             enable row level security;
alter table public.experience         enable row level security;
alter table public.education          enable row level security;
alter table public.projects           enable row level security;
alter table public.project_images     enable row level security;
alter table public.certificates       enable row level security;
alter table public.testimonials       enable row level security;
alter table public.messages           enable row level security;

grant usage on schema public to anon, authenticated;
grant select on
  public.profile, public.settings, public.ui_text, public.section_visibility, public.social_links,
  public.skill_categories, public.skills, public.experience, public.education,
  public.projects, public.project_images, public.certificates, public.testimonials
to anon, authenticated;
grant insert on public.messages to anon, authenticated;

-- Single-row tables have no visibility flag: readable by everyone.
drop policy if exists "Public can read profile" on public.profile;
create policy "Public can read profile" on public.profile
  for select to anon, authenticated using (true);

drop policy if exists "Public can read settings" on public.settings;
create policy "Public can read settings" on public.settings
  for select to anon, authenticated using (true);

drop policy if exists "Public can read ui text" on public.ui_text;
create policy "Public can read ui text" on public.ui_text
  for select to anon, authenticated using (true);

-- Tables where a row is public when is_visible = true.
do $$
declare
  t text;
begin
  foreach t in array array[
    'section_visibility', 'social_links', 'skill_categories', 'experience',
    'education', 'projects', 'certificates', 'testimonials'
  ]
  loop
    execute format('drop policy if exists "Public can read visible rows" on public.%I', t);
    execute format(
      'create policy "Public can read visible rows" on public.%I for select to anon, authenticated using (is_visible)',
      t
    );
  end loop;
end;
$$;

-- Child rows are public only when they and their parent are visible.
drop policy if exists "Public can read visible rows" on public.skills;
create policy "Public can read visible rows" on public.skills
  for select to anon, authenticated
  using (
    is_visible
    and exists (
      select 1 from public.skill_categories c
      where c.id = skills.category_id and c.is_visible
    )
  );

drop policy if exists "Public can read visible rows" on public.project_images;
create policy "Public can read visible rows" on public.project_images
  for select to anon, authenticated
  using (
    is_visible
    and exists (
      select 1 from public.projects p
      where p.id = project_images.project_id and p.is_visible
    )
  );

-- Contact form: anyone may insert a new, unread message. Nobody can read
-- messages through the public API; the admin reads them via the server.
drop policy if exists "Public can send messages" on public.messages;
create policy "Public can send messages" on public.messages
  for insert to anon, authenticated
  with check (is_read = false);


-- ---------------------------------------------------------------------
-- Storage buckets: public read, server-only write
-- ---------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values
  ('avatars',      'avatars',      true, 5242880,
     array['image/jpeg', 'image/png', 'image/webp', 'image/gif']),
  ('projects',     'projects',     true, 5242880,
     array['image/jpeg', 'image/png', 'image/webp', 'image/gif']),
  ('certificates', 'certificates', true, 5242880,
     array['image/jpeg', 'image/png', 'image/webp', 'image/gif']),
  ('documents',    'documents',    true, 10485760,
     array['application/pdf', 'image/png', 'image/x-icon', 'image/vnd.microsoft.icon'])
on conflict (id) do update set
  public             = excluded.public,
  file_size_limit    = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- Anyone may read files in these buckets. There are no insert, update or
-- delete policies, so only the service role (the Express API) can write.
drop policy if exists "Public can read portfolio files" on storage.objects;
create policy "Public can read portfolio files" on storage.objects
  for select to anon, authenticated
  using (bucket_id in ('avatars', 'projects', 'certificates', 'documents'));
